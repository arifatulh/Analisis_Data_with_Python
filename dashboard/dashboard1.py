col1, col2 = st.columns(2)
#daily transaction tren
with col1:
    st.subheader("Daily Transaction Trend")
    daily_transactions = main_df.groupby('order_purchase_timestamp')['order_id'].count().reset_index()
    daily_transactions = daily_transactions.rename(columns={'order_id': 'Transaction Count'})

    # line plot
    fig, ax = plt.subplots(figsize=(10, 6))
    sns.lineplot(x='order_purchase_timestamp', y='Transaction Count', data=daily_transactions, ax=ax)
    ax.fill_between(daily_transactions['order_purchase_timestamp'], daily_transactions['Transaction Count'], alpha=0.3)
    ax.set_xlabel("Date")
    ax.set_ylabel("Number of Transactions")
    plt.xticks(rotation=45)
    st.pyplot(fig)

# Daily revenue trend

with col2:
    st.subheader("Daily Revenue Trend")
    daily_revenue = main_df.groupby('order_purchase_timestamp')['price'].sum().reset_index()
    daily_revenue = daily_revenue.rename(columns={'price': 'Revenue'})

    # lineplot
    fig, ax = plt.subplots(figsize=(10, 6))
    sns.lineplot(x='order_purchase_timestamp', y='Revenue', data=daily_revenue, ax=ax)
    ax.fill_between(daily_revenue['order_purchase_timestamp'], daily_revenue['Revenue'], alpha=0.3)
    ax.set_xlabel("Date")
    ax.set_ylabel("Revenue")
    plt.xticks(rotation=45)
    st.pyplot(fig)

# mothly trend analysis
col1, col2 = st.columns(2)

#transaction trend
with col1:
    st.subheader("Monthly Transaction Trend")

    df['order_purchase_timestamp'] = pd.to_datetime(df['order_purchase_timestamp'])
    filtered_df = df[df['order_purchase_timestamp'].dt.year.isin(selected_years)]
    monthly_transactions = filtered_df.groupby(filtered_df['order_purchase_timestamp'].dt.to_period('M'))['order_id'].count().reset_index()
    monthly_transactions.columns = ['Month-Year', 'Transaction Count']
    monthly_transactions['Month-Year'] = monthly_transactions['Month-Year'].astype(str)

    fig, ax = plt.subplots(figsize=(8, 6))

    # Create line plot
    ax.plot(monthly_transactions['Month-Year'], monthly_transactions['Transaction Count'], marker='o', linestyle='-')
    ax.fill_between(monthly_transactions['Month-Year'], monthly_transactions['Transaction Count'], alpha=0.3)

    plt.xticks(rotation=90)
    ax.set_xlabel('Month')
    ax.set_ylabel('Transaction Count')
    st.pyplot(fig)

#revenue trend
