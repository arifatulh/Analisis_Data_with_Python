    # Group by month and year and sum revenue
    monthly_revenue = filtered_df.groupby(filtered_df['order_purchase_timestamp'].dt.to_period('M'))['price'].sum().reset_index()
    monthly_revenue.columns = ['Month-Year', 'Total Revenue']
    monthly_revenue['Month-Year'] = monthly_revenue['Month-Year'].astype(str)

    fig, ax = plt.subplots(figsize=(8, 6))

    # Create line plot
    ax.plot(monthly_revenue['Month-Year'], monthly_revenue['Total Revenue'], marker='o', linestyle='-')
    ax.fill_between(monthly_revenue['Month-Year'], monthly_revenue['Total Revenue'], alpha=0.3)

    plt.xticks(rotation=90)
    ax.set_xlabel('Month')
    ax.set_ylabel('Total Revenue')
